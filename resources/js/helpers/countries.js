const names = {};

export const countryName = (code, language = "fr") => {
  names[language] ??= new Intl.DisplayNames([language], { type: "region" });
  return names[language].of(code);
};

// Options de liste triées dans la langue affichée
export const countryOptions = (language) =>
  COUNTRY_CODES.map((code) => ({
    value: code,
    label: countryName(code, language),
  })).sort((a, b) => a.label.localeCompare(b.label, language));
